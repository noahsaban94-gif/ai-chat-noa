/**
 * חילוץ מזהה סרטון מתוך כתובת יוטיוב
 */
export function extractYouTubeVideoId(url: string): string | null {
  if (!url) return null
  const cleanUrl = url.trim()

  // Match: youtube.com/watch?v=ID or youtube.com/v/ID or youtube.com/embed/ID
  const regExp = /(?:youtube\.com\/(?:[^\/]+\/.+\/|(?:v|e(?:mbed)?)\/|.*[?&]v=)|youtu\.be\/)([^"&?\/\s]{11})/i
  const match = cleanUrl.match(regExp)

  if (match && match[1]) {
    return match[1]
  }

  // Fallback: check if already 11-char ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(cleanUrl)) {
    return cleanUrl
  }

  return null
}

/**
 * איתור סרטונים ומוצרים לפי מילות מפתח בטקסט
 */
export function findTrainingVideos(query: string): TrainingProduct[] {
  if (!query || !query.trim()) return []

  const normalizedQuery = query.toLowerCase().trim()
  const results: { product: TrainingProduct; score: number }[] = []

  for (const product of TRAINING_PRODUCTS) {
    let score = 0

    // Exact SKU match in query (highest priority)
    if (product.sku && normalizedQuery.includes(product.sku.toLowerCase())) {
      score += 50
    }

    // Match in product name
    if (product.name.toLowerCase().includes(normalizedQuery)) {
      score += 20
    } else if (normalizedQuery.includes(product.name.toLowerCase())) {
      score += 15
    }

    // Match in keywords
    for (const keyword of product.keywords) {
      const lowerKw = keyword.toLowerCase()
      if (normalizedQuery.includes(lowerKw)) {
        score += 8
      } else if (lowerKw.includes(normalizedQuery)) {
        score += 4
      }
    }

    // Match in category
    if (normalizedQuery.includes(product.category.toLowerCase())) {
      score += 4
    }

    // Match in description
    if (product.description.toLowerCase().includes(normalizedQuery)) {
      score += 2
    }

    if (score > 0) {
      results.push({ product, score })
    }
  }

  results.sort((a, b) => b.score - a.score)
  return results.map((r) => r.product)
}
